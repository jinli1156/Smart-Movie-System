CREATE TABLE souvenir_ticket (
 id VARCHAR(36) PRIMARY KEY,
 order_id BIGINT NOT NULL,
 user_id BIGINT NOT NULL,
 style VARCHAR(24) NOT NULL,
 note VARCHAR(120) NOT NULL DEFAULT '',
 status VARCHAR(16) NOT NULL,
 snapshot TEXT NOT NULL,
 headline VARCHAR(80),
 caption VARCHAR(160),
 image_prompt TEXT,
 provider_result TEXT,
 storage_key VARCHAR(80),
 error_message VARCHAR(200),
 retryable BOOLEAN NOT NULL DEFAULT FALSE,
 attempts INT NOT NULL DEFAULT 1,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 UNIQUE KEY uk_souvenir_order_style (order_id, style),
 INDEX idx_souvenir_queue (status, created_at),
 INDEX idx_souvenir_owner (user_id, created_at),
 CONSTRAINT fk_souvenir_order FOREIGN KEY (order_id) REFERENCES ticket_order(id),
 CONSTRAINT fk_souvenir_user FOREIGN KEY (user_id) REFERENCES `user`(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='基于真实订单的 AI 观影纪念卡，非入场凭证';
