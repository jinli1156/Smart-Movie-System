CREATE TABLE personal_movie_poster (
 id VARCHAR(36) PRIMARY KEY,
 user_id BIGINT NOT NULL,
 request_id VARCHAR(36) NOT NULL,
 request_hash CHAR(64) NOT NULL,
 movie_title VARCHAR(80) NOT NULL DEFAULT '',
 style VARCHAR(24) NOT NULL,
 prompt VARCHAR(1000) NOT NULL DEFAULT '',
 ratio VARCHAR(8) NOT NULL,
 has_portrait BOOLEAN NOT NULL DEFAULT FALSE,
 portrait_key VARCHAR(80),
 status VARCHAR(24) NOT NULL,
 provider_result TEXT,
 storage_key VARCHAR(80),
 error_message VARCHAR(200),
 retryable BOOLEAN NOT NULL DEFAULT FALSE,
 attempts INT NOT NULL DEFAULT 1,
 created_at DATETIME(6) NOT NULL,
 updated_at DATETIME(6) NOT NULL,
 UNIQUE KEY uk_personal_poster_request (user_id, request_id),
 INDEX idx_personal_poster_queue (status, created_at),
 INDEX idx_personal_poster_owner (user_id, created_at),
 CONSTRAINT fk_personal_poster_user FOREIGN KEY (user_id) REFERENCES `user`(id)
) ENGINE=InnoDB DEFAULT CHARSET=utf8mb4 COLLATE=utf8mb4_unicode_ci COMMENT='用户专属电影风格海报与私有照片引用';
